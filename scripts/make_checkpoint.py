#!/usr/bin/env python3
"""Generate Checkpoint+Mainnet.swift from a live LBRY hub.

Picks a block `--depth` below the hub's tip (default 1000, ~1.7 days) so it's
well buried, fetches it and its parent, and writes Checkpoint+Mainnet.swift:

    python3 scripts/make_checkpoint.py

The Swift file is only written if a hub answers, so a failed run leaves it untouched.

Cross-check the printed hash against a block explorer before committing.
Uses only the standard library.
"""
import argparse
import hashlib
import json
import socket
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "Packages/LBRYKit/Sources/LBRYKit/Chain/Checkpoint+Mainnet.swift"

# Current list per lbry-sdk-ng (Oct 2026); the old spv1x.lbry.com hubs are gone.
DEFAULT_HUBS = [
    "a-hub1.odysee.com", "b-hub1.odysee.com", "c-hub1.odysee.com", "s-hub1.odysee.com",
    "hub.lbry.grin.io", "hub.lizard.technology", "s1.lbry.network",
]


class Hub:
    def __init__(self, host, port, timeout=5):
        self.sock = socket.create_connection((host, port), timeout=timeout)
        self.file = self.sock.makefile("rwb")
        self.next_id = 0

    def call(self, method, params):
        self.next_id += 1
        self.file.write(json.dumps({"jsonrpc": "2.0", "id": self.next_id,
                                    "method": method, "params": params}).encode() + b"\n")
        self.file.flush()
        while True:
            msg = json.loads(self.file.readline())
            if msg.get("id") == self.next_id:
                if msg.get("error"):
                    raise RuntimeError(msg["error"])
                return msg["result"]


def block_hash(raw):
    return hashlib.sha256(hashlib.sha256(raw).digest()).digest()[::-1].hex()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hub", help="host[:port]; default tries the lbry-sdk hub list")
    ap.add_argument("--depth", type=int, default=1000)
    ap.add_argument("--stdout", action="store_true", help="print instead of writing the Swift file")
    args = ap.parse_args()

    candidates = [args.hub] if args.hub else DEFAULT_HUBS
    for candidate in candidates:
        host, _, port = candidate.partition(":")
        try:
            hub = Hub(host, int(port or 50001))
            hub.call("server.version", ["Carrel checkpoint script", "0.113.0"])
            tip = hub.call("blockchain.headers.subscribe", [True])["height"]
            height = tip - args.depth
            raw = bytes.fromhex(hub.call("blockchain.block.headers", [height - 1, 2, 0, False])["hex"])
            break
        except Exception as e:  # try the next hub
            print(f"{candidate}: {e}", file=sys.stderr)
    else:
        sys.exit("no hub reachable")

    prev, cur = raw[:112], raw[112:224]
    assert cur[4:36] == hashlib.sha256(hashlib.sha256(prev).digest()).digest(), "headers don't link"
    swift = f"""// Generated by scripts/make_checkpoint.py from {host} — regenerate before each release.
// Hub tip was {tip}; checkpoint is {args.depth} blocks deep.

extension Checkpoint {{
    public static let mainnet: Checkpoint? = Checkpoint(
        height: {height},
        previousHeaderHex: "{prev.hex()}",
        headerHex: "{cur.hex()}",
        hash: "{block_hash(cur)}"
    )
}}
"""
    if args.stdout:
        print(swift, end="")
    else:
        OUT.write_text(swift)
        print(f"wrote {OUT.name}: height {height}, hash {block_hash(cur)} (from {host})", file=sys.stderr)


if __name__ == "__main__":
    main()
